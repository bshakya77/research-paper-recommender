"""Stage 5 CLI: analyze an indexed paper with Groq and Gemini fallback."""

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from src.config import settings
from src.generation import analyze_paper


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate a grounded analysis of one paper")
    parser.add_argument("--paper-id", required=True, help="Canonical paper ID, such as an arXiv ID")
    parser.add_argument("--question", help="Optional question or analysis focus")
    parser.add_argument("--top-k", type=int, default=settings.top_k_retrieval,
                        help="Number of evidence chunks to retrieve")
    args = parser.parse_args()

    result = analyze_paper(args.paper_id, question=args.question, top_k=args.top_k)
    print(f"# {result.title} ({result.paper_id})")
    print(f"Generated by: {result.provider} / {result.model}")
    print(f"\nQuestion: {result.question}\n")
    print(result.analysis)
    print("\n## Retrieved sources")
    for number, ref in enumerate(result.evidence_refs, start=1):
        print(f"[{number}] {ref.paper_id} — {ref.section}, page {ref.page}: {ref.snippet}")


if __name__ == "__main__":
    try:
        main()
    except (RuntimeError, ValueError, FileNotFoundError) as exc:
        sys.exit(str(exc))
